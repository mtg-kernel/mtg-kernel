"""Regenerate only the FlatV9 (Cube, M2 T6) feature pins from features_v12.py."""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
from mtg_kernel_rl import features_v12 as features


def generate() -> None:
    directory = Path(__file__).resolve().parent
    source_hash = hashlib.sha256(Path(features.__file__).read_bytes()).hexdigest()
    descriptor = {
        "schema": "flat-policy-v9-feature-contract-1",
        "rich_observation_schema": 7,
        "legal_action_schema": 5,
        "feature_schema_version": features.FEATURE_SCHEMA_VERSION,
        "feature_registry_version": features.FEATURE_REGISTRY_VERSION,
        "feature_contract_digest": features.feature_contract_fingerprint(),
        "feature_encoding_digest": features.encoding_contract_fingerprint(),
        "features_source_path": "python/mtg_kernel_rl/features_v12.py",
        "features_source_sha256": source_hash,
        "predecessor_features_source_path": "python/mtg_kernel_rl/features_v11.py",
        "model_contract_version": features.MODEL_CONTRACT_VERSION,
        "dimensions": {
            "state": features.STATE_FEATURE_DIM,
            "object": features.OBJECT_FEATURE_DIM,
            "edge": features.EDGE_FEATURE_DIM,
            "action": features.ACTION_FEATURE_DIM,
            "action_ref": features.ACTION_REF_FEATURE_DIM,
            "object_groups": 20,
        },
        "additions": {
            "object_columns": {"first": features.PREDECESSOR_OBJECT_FEATURE_DIM,
                               "names": list(features.OBJECT_COLUMNS)},
            "state_columns": {"first": features.PREDECESSOR_STATE_FEATURE_DIM,
                              "names": list(features.STATE_COLUMNS)},
            "relaxed_observation": "the FlatV8 tensors of the observation with the FlatV9 fields cleared",
            "extension": "extensions.flat_v9: per public card keywords, planeswalker, loyalty and turn ages; "
                         "attack count; history facts",
        },
        "design": "collab LANES/lead/reviews/cube-briefs-20261122/m2-design-hp/M2-DESIGN.md section 2d; "
                  "LANES/cube-m2-20261127/DECISIONS-1.md T6 with RULING-DECISIONS-1.md",
        "status": "provisional: the lead freezes the column list, age bounds, ordering and visibility "
                  "before goldens",
    }
    descriptor_bytes = (json.dumps(descriptor, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode()
    (directory / "feature_contract_v9.json").write_bytes(descriptor_bytes)
    values = {
        "FEATURE_SCHEMA_VERSION_V9": features.FEATURE_SCHEMA_VERSION,
        "FEATURE_REGISTRY_VERSION_V9": features.FEATURE_REGISTRY_VERSION,
        "FEATURE_CONTRACT_DIGEST_V9": features.feature_contract_fingerprint(),
        "FEATURE_ENCODING_DIGEST_V9": features.encoding_contract_fingerprint(),
        "FEATURES_SOURCE_SHA256_V9": source_hash,
        "FEATURE_DESCRIPTOR_SHA256_V9": hashlib.sha256(descriptor_bytes).hexdigest(),
    }
    lines = ["// Generated by data/flat_policy_v9/generate_contract.py. V8, V7 and V4 pins are separate."]
    lines += [f'pub(crate) const {key}: &str = "{value}";' for key, value in values.items()]
    (directory / "feature_identity.rs").write_bytes(("\n".join(lines) + "\n").encode())
    print(json.dumps(values, sort_keys=True))


if __name__ == "__main__":
    generate()
